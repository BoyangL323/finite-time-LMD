function dydt = DavydovD2Rabi(t,y,MM,Ns,Nb,H,VV1,lambda_k,omega_k)

AA=reshape(y(1:MM*Ns),MM,Ns);
FF=reshape(y((MM*Ns+1):(MM*Ns+Nb*MM)),Nb,MM).';

tmpff=conj(FF)*FF.';
dtmp = real(diag(tmpff));
mff=exp(tmpff-0.5*(dtmp+dtmp.')) + 1e-10*eye(MM);

Matt=[ ...
    kron(eye(Ns),mff), ...
    kron(AA.',conj(FF)).*kron(kron(ones(Ns,1),mff),ones(1,Nb)); ...
    kron(conj(AA),FF.').*kron(kron(ones(1,Ns),mff),ones(Nb,1)), ...
    kron((conj(AA)*AA.').*mff,ones(Nb,Nb)).* ...
    (kron(ones(MM,MM),eye(Nb)) + ...
     kron(kron(ones(1,MM),conj(FF)),ones(Nb,1)).* ...
     kron(kron(ones(MM,1),FF.'),ones(1,Nb))) ...
    ];

% phonons only
lambda_kt1 = lambda_k.*exp(-1i*omega_k*t);
FL1        = FF*lambda_kt1.';

ACVAT1  = conj(AA)*VV1*AA.';
ACVdAT1 = conj(AA)*VV1'*AA.';

colAlj = reshape( ...
    mff*AA*H.' + ...
    0.5*(diag(conj(FL1))*mff*AA*VV1.' + mff*diag(FL1)*AA*conj(VV1)), ...
    [],1);

colFlp = reshape(( ...
    ((((conj(AA)*H*AA.').*mff) + ...
      0.5*(diag(conj(FL1))*(ACVAT1.*mff) + (ACVdAT1.*mff)*diag(FL1)))*FF) + ...
      0.5*(ACVAT1.*mff)*repmat(conj(lambda_kt1),MM,1) ...
    ).',[],1);

tmpdy = Matt\(-1i*[colAlj;colFlp]);

anj = reshape(tmpdy(1:MM*Ns),MM,Ns);
dFF = reshape(tmpdy((MM*Ns+1):(MM*Ns+Nb*MM)),Nb,MM).';

dAA = anj + AA.*real(sum(dFF.*conj(FF),2));

dydt = [reshape(dAA,[],1); reshape(dFF.',[],1)];
end